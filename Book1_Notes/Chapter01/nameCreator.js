let normalName = 'Sahara'; // 'Sahara' is a value
let javaScriptName = normalName + 'Script'; // + is an operator (concat)
// the right-hand side is an expression
// and let is a keyword in JavaScript
console.log('Your JavaScript Name is ' + javaScriptName);


